"""Check opt-in PTX atomic histogram fallback; optional compiled PTX verification.

The source guard is not proof that NVCC actually emits atom.shared:
the optional --ptx text generated by cuobjdump checks that separately.
"""
import argparse
import re
from pathlib import Path

p = argparse.ArgumentParser()
p.add_argument("--source", type=Path, required=True)
p.add_argument("--ptx", type=Path)
args = p.parse_args()

text = args.source.read_text(encoding="utf-8")
start = text.index("static __global__ void top_k_radix_histogram(")
end = text.index("static __global__ void top_k_radix_select(", start)
body = text[start:end]
guarded = body.split("#ifdef GGML_CUDA_ZLUDA_ATOM_HISTOGRAM", 1)[1].split("#else", 1)[0]
assert "asm volatile" in guarded
assert "atom.shared.add.u32" in guarded
assert "__cvta_generic_to_shared" in guarded
assert '"atom.shared.add.u32' in guarded and not re.search(r'asm volatile\("red', guarded)
assert "atomicAdd(&histogram[" in body.split("#else", 1)[1]
print("Source: explicit opt-in atom.shared histogram branch present")

if args.ptx:
    dumped = args.ptx.read_text(encoding="utf-8", errors="replace")
    # cuobjdump emits .entry names with template args encoded into mangled symbol.
    entries = re.split(r"(?=\.visible\s+\.entry\s+|\.entry\s+)", dumped)
    kernels = [part for part in entries if re.search(r"\.entry\s+[^\s(]*top_k_radix_histogram", part)]
    assert kernels, "No top_k_radix_histogram PTX entry found in CUDA artifact"
    for kernel in kernels:
        assert re.search(r"\batom\.shared\.add\.u32\b", kernel), "Expected inline shared atom absent"
        assert not re.search(r"\bred\.shared\.add\.u32\b", kernel), "Unsupported shared red still present"
    print(f"Compiled PTX: {len(kernels)} histogram variants use atom.shared.add; none uses red.shared.add")
